// Reserved for technical strings that must intentionally remain unchanged.
export const BPMN_IDENTITY_SAFE_KEYS = new Set<string>();

export function translateBpmn(
  locale: Locale,
  template: string,
  replacements: Readonly<Record<string, string | number>> = {},
): string {
  const translated =
    locale === "ru" ? (RU_BPMN_TRANSLATIONS[template] ?? template) : template;
  return translated.replace(/\{([^}]+)\}/gu, (match, name: string) =>
    Object.hasOwn(replacements, name) ? String(replacements[name]) : match,
  );
}

function russianTranslate(
  template: string,
  replacements?: Readonly<Record<string, string | number>>,
): string {
  return translateBpmn("ru", template, replacements);
}

export const russianBpmnTranslateModule = {
  translate: ["value", russianTranslate],
};
